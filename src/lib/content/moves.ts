const byId = new Map(MOVES.map((m) => [m.id, m]));

export function getMove(id: string) {
  return byId.get(id);
}

export function moveNeighbors(id: string) {
  const index = MOVES.findIndex((m) => m.id === id);
  return {
    prev: index > 0 ? MOVES[index - 1] : null,
    next: index >= 0 && index < MOVES.length - 1 ? MOVES[index + 1] : null,
    index,
    total: MOVES.length,
  };
}

export function moveForSection(chapterId: string, sectionId: string) {
  return MOVES.find((m) => m.chapterId === chapterId && m.sectionId === sectionId);
}

export function moveForProblem(no: string) {
  return MOVES.find((m) => m.problems.includes(no));
}

export function searchMoves(query: string, limit = 8) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const hits: { id: string; title: string; snippet: string }[] = [];
  for (const m of MOVES) {
    const text = `${m.section} ${m.title} ${m.job} ${m.why} ${m.trap} ${m.problems.join(" ")}`.toLowerCase();
    if (!text.includes(q)) continue;
    hits.push({ id: m.id, title: `${m.section} ${m.title}`, snippet: m.job });
    if (hits.length >= limit) break;
  }
  return hits;
}
